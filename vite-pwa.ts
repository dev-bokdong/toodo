/**
 * Makes the web build (`--mode web`) an installable app: a web app manifest with the icons
 * in `src/web/pwa`, and a service worker that keeps the app shell (the built HTML, scripts,
 * styles, and icons) for offline starts and shows the server's pushes as notifications (see
 * `src/web/push.ts`).
 *
 * The service worker never answers `/api` or `/mcp` requests: commands, events, and files
 * always go to the server. It precaches exactly the files of this build, so a new build
 * installs a new cache and drops the old one.
 *
 * The icons come from `src-tauri/icons/icon.svg` and its maskable variant
 * `src/web/pwa/icon-maskable.svg` (artwork inside the safe zone, full-bleed background):
 * `npx tauri icon <svg> -o <dir>` renders `icon.png` (512 px); the 192 px icons and the
 * 180 px `apple-touch-icon.png` (`ios/AppIcon-60x60@3x.png` of the maskable one) are
 * resized copies.
 */
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import path from "node:path";
import type { Plugin } from "vite";

const iconDir = path.resolve(import.meta.dirname, "src/web/pwa");

const icons = [
  { file: "icon-192.png", sizes: "192x192", purpose: "any" },
  { file: "icon-512.png", sizes: "512x512", purpose: "any" },
  { file: "icon-maskable-192.png", sizes: "192x192", purpose: "maskable" },
  { file: "icon-maskable-512.png", sizes: "512x512", purpose: "maskable" },
] as const;

const appleTouchIcon = "apple-touch-icon.png";

const manifest = {
  id: "/",
  name: "Toodo",
  short_name: "Toodo",
  description: "Plan tasks, implement them in herdr, and keep the record.",
  start_url: "/",
  scope: "/",
  display: "standalone",
  background_color: "#ffffff",
  theme_color: "#ffffff",
  icons: icons.map(({ file, sizes, purpose }) => ({ src: `/pwa/${file}`, sizes, type: "image/png", purpose })),
};

/** Paths the service worker leaves to the network: the server's API and MCP endpoint. */
const serverPaths = ["/api", "/mcp"];

/** The icon of push notifications, also their badge. */
const notificationIcon = "/pwa/icon-192.png";

function serviceWorker(cacheName: string, shell: string[]): string {
  return `// Generated by vite-pwa.ts for this build.
const CACHE = ${JSON.stringify(cacheName)};
const SHELL = ${JSON.stringify(shell)};
const SERVER_PATHS = ${JSON.stringify(serverPaths)};
const NOTIFICATION_ICON = ${JSON.stringify(notificationIcon)};
// The message that asks an open page to show a task; see listenForOpenTask in src/web/push.ts.
const OPEN_TASK = "toodo-open-task";

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(SHELL.map((path) => new Request(path, { cache: "reload" })))),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((names) => Promise.all(names.filter((name) => name !== CACHE).map((name) => caches.delete(name))))
      .then(() => self.clients.claim()),
  );
});

function isServerPath(pathname) {
  return SERVER_PATHS.some((path) => pathname === path || pathname.startsWith(path + "/"));
}

// A proxy in front of the server, such as a tunnel, answers for it with its own error page;
// see isGatewayFailure in src/web/connection.ts.
function isGatewayFailure(response) {
  const status = response.status;
  const gateway = status === 502 || status === 503 || status === 504 || (status >= 520 && status <= 530);
  return gateway && !(response.headers.get("Content-Type") ?? "").includes("application/json");
}

function cachedApp() {
  return caches.match("/", { cacheName: CACHE });
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== "GET" || url.origin !== self.location.origin || isServerPath(url.pathname)) {
    return;
  }
  if (request.mode === "navigate") {
    // The server answers every page with the app; while it is unreachable, the cached app
    // starts instead and shows the offline screen.
    event.respondWith(
      fetch(request)
        .then((response) => (isGatewayFailure(response) ? cachedApp().then((app) => app ?? response) : response))
        .catch(() => cachedApp()),
    );
    return;
  }
  if (SHELL.includes(url.pathname)) {
    event.respondWith(caches.match(request, { cacheName: CACHE }).then((cached) => cached ?? fetch(request)));
  }
});

// Every push shows a notification, a plain one for a message that cannot be read: Safari ends
// the subscription of a site whose pushes show none.
function pushMessage(data) {
  try {
    const message = data ? data.json() : null;
    return message !== null && typeof message === "object" ? message : {};
  } catch {
    return {};
  }
}

self.addEventListener("push", (event) => {
  const message = pushMessage(event.data);
  const options = {
    body: typeof message.body === "string" ? message.body : "Open Toodo to see what changed.",
    data: { taskId: typeof message.taskId === "number" ? message.taskId : null },
    icon: NOTIFICATION_ICON,
    badge: NOTIFICATION_ICON,
  };
  if (typeof message.tag === "string" && message.tag !== "") {
    // A newer alert replaces the shown one with the same tag, and still alerts.
    options.tag = message.tag;
    options.renotify = true;
  }
  const title = typeof message.title === "string" && message.title !== "" ? message.title : "Toodo";
  event.waitUntil(self.registration.showNotification(title, options));
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const taskId = event.notification.data?.taskId ?? null;
  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((windows) => {
      // The most recently focused window comes first.
      const open = windows[0];
      if (!open) {
        return self.clients.openWindow(taskId === null ? "/" : "/?task=" + taskId);
      }
      if (taskId !== null) {
        open.postMessage({ type: OPEN_TASK, taskId });
      }
      return open.focus();
    }),
  );
});

// The browser renewed or ended the subscription. Without an access token the worker cannot
// tell the server; the app sends the browser's subscription again when it next starts. If
// the browser made no new one, make it, with the same key.
self.addEventListener("pushsubscriptionchange", (event) => {
  const options = event.oldSubscription?.options;
  if (event.newSubscription || !options) {
    return;
  }
  event.waitUntil(self.registration.pushManager.subscribe(options));
});
`;
}

export function pwa(): Plugin {
  return {
    name: "toodo-pwa",
    apply: "build",
    // After Vite's own plugins, so the bundle already holds every built file.
    enforce: "post",
    transformIndexHtml() {
      return [
        // Browsers fetch the manifest without cookies unless asked to; with them, it still
        // loads behind a proxy that authenticates by cookie (see docs/server.md).
        {
          tag: "link",
          attrs: { rel: "manifest", href: "/manifest.webmanifest", crossorigin: "use-credentials" },
          injectTo: "head",
        },
        { tag: "link", attrs: { rel: "apple-touch-icon", href: `/pwa/${appleTouchIcon}` }, injectTo: "head" },
        {
          tag: "meta",
          attrs: { name: "theme-color", content: "#ffffff", media: "(prefers-color-scheme: light)" },
          injectTo: "head",
        },
        {
          tag: "meta",
          attrs: { name: "theme-color", content: "#0a0a0a", media: "(prefers-color-scheme: dark)" },
          injectTo: "head",
        },
      ];
    },
    generateBundle(_options, bundle) {
      const iconPaths = [...icons.map((icon) => icon.file), appleTouchIcon].map((file) => `pwa/${file}`);
      for (const fileName of iconPaths) {
        this.emitFile({ type: "asset", fileName, source: readFileSync(path.join(iconDir, path.basename(fileName))) });
      }
      this.emitFile({
        type: "asset",
        fileName: "manifest.webmanifest",
        source: `${JSON.stringify(manifest, null, 2)}\n`,
      });
      const built = Object.keys(bundle)
        .filter((file) => file !== "index.html" && !file.endsWith(".map"))
        .map((file) => `/${file}`);
      // `/` is the app itself; the favicon comes from `public/`, outside the bundle, and the
      // files emitted here are not in `bundle` yet.
      const shell = [
        ...new Set(["/", "/favicon.svg", "/manifest.webmanifest", ...iconPaths.map((file) => `/${file}`), ...built]),
      ].sort();
      const version = createHash("sha256").update(JSON.stringify(shell)).digest("hex").slice(0, 16);
      this.emitFile({ type: "asset", fileName: "sw.js", source: serviceWorker(`toodo-shell-${version}`, shell) });
    },
  };
}
