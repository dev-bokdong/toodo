/**
 * Makes the web build (`--mode web`) an installable app: a web app manifest with the icons
 * in `src/web/pwa`, and a service worker that keeps the app shell (the built HTML, scripts,
 * styles, and icons) for offline starts.
 *
 * The service worker never answers `/api` or `/mcp` requests: commands, events, and files
 * always go to the server. It precaches exactly the files of this build, so a new build
 * installs a new cache and drops the old one.
 *
 * The icons come from `src-tauri/icons/icon.svg` and its maskable variant
 * `src/web/pwa/icon-maskable.svg` (artwork inside the safe zone, full-bleed background):
 * `npx tauri icon <svg> -o <dir>` renders `icon.png` (512 px); the 192 px icons and the
 * 180 px `apple-touch-icon.png` (`ios/AppIcon-60x60@3x.png` of the maskable one) are
 * resized copies.
 */
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import path from "node:path";
import type { Plugin } from "vite";

const iconDir = path.resolve(import.meta.dirname, "src/web/pwa");

const icons = [
  { file: "icon-192.png", sizes: "192x192", purpose: "any" },
  { file: "icon-512.png", sizes: "512x512", purpose: "any" },
  { file: "icon-maskable-192.png", sizes: "192x192", purpose: "maskable" },
  { file: "icon-maskable-512.png", sizes: "512x512", purpose: "maskable" },
] as const;

const appleTouchIcon = "apple-touch-icon.png";

const manifest = {
  id: "/",
  name: "Toodo",
  short_name: "Toodo",
  description: "Plan tasks, implement them in herdr, and keep the record.",
  start_url: "/",
  scope: "/",
  display: "standalone",
  background_color: "#ffffff",
  theme_color: "#ffffff",
  icons: icons.map(({ file, sizes, purpose }) => ({ src: `/pwa/${file}`, sizes, type: "image/png", purpose })),
};

/** Paths the service worker leaves to the network: the server's API and MCP endpoint. */
const serverPaths = ["/api", "/mcp"];

function serviceWorker(cacheName: string, shell: string[]): string {
  return `// Generated by vite-pwa.ts for this build.
const CACHE = ${JSON.stringify(cacheName)};
const SHELL = ${JSON.stringify(shell)};
const SERVER_PATHS = ${JSON.stringify(serverPaths)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(SHELL.map((path) => new Request(path, { cache: "reload" })))),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((names) => Promise.all(names.filter((name) => name !== CACHE).map((name) => caches.delete(name))))
      .then(() => self.clients.claim()),
  );
});

function isServerPath(pathname) {
  return SERVER_PATHS.some((path) => pathname === path || pathname.startsWith(path + "/"));
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== "GET" || url.origin !== self.location.origin || isServerPath(url.pathname)) {
    return;
  }
  if (request.mode === "navigate") {
    // The server answers every page with the app; offline, the cached app starts instead.
    event.respondWith(fetch(request).catch(() => caches.match("/", { cacheName: CACHE })));
    return;
  }
  if (SHELL.includes(url.pathname)) {
    event.respondWith(caches.match(request, { cacheName: CACHE }).then((cached) => cached ?? fetch(request)));
  }
});
`;
}

export function pwa(): Plugin {
  return {
    name: "toodo-pwa",
    apply: "build",
    // After Vite's own plugins, so the bundle already holds every built file.
    enforce: "post",
    transformIndexHtml() {
      return [
        { tag: "link", attrs: { rel: "manifest", href: "/manifest.webmanifest" }, injectTo: "head" },
        { tag: "link", attrs: { rel: "apple-touch-icon", href: `/pwa/${appleTouchIcon}` }, injectTo: "head" },
        {
          tag: "meta",
          attrs: { name: "theme-color", content: "#ffffff", media: "(prefers-color-scheme: light)" },
          injectTo: "head",
        },
        {
          tag: "meta",
          attrs: { name: "theme-color", content: "#0a0a0a", media: "(prefers-color-scheme: dark)" },
          injectTo: "head",
        },
      ];
    },
    generateBundle(_options, bundle) {
      const iconPaths = [...icons.map((icon) => icon.file), appleTouchIcon].map((file) => `pwa/${file}`);
      for (const fileName of iconPaths) {
        this.emitFile({ type: "asset", fileName, source: readFileSync(path.join(iconDir, path.basename(fileName))) });
      }
      this.emitFile({
        type: "asset",
        fileName: "manifest.webmanifest",
        source: `${JSON.stringify(manifest, null, 2)}\n`,
      });
      const built = Object.keys(bundle)
        .filter((file) => file !== "index.html" && !file.endsWith(".map"))
        .map((file) => `/${file}`);
      // `/` is the app itself; the favicon comes from `public/`, outside the bundle, and the
      // files emitted here are not in `bundle` yet.
      const shell = [
        ...new Set(["/", "/favicon.svg", "/manifest.webmanifest", ...iconPaths.map((file) => `/${file}`), ...built]),
      ].sort();
      const version = createHash("sha256").update(JSON.stringify(shell)).digest("hex").slice(0, 16);
      this.emitFile({ type: "asset", fileName: "sw.js", source: serviceWorker(`toodo-shell-${version}`, shell) });
    },
  };
}
