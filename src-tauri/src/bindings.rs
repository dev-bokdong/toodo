//! Generates `src/lib/bindings.ts`, the frontend's typed client of the commands the server
//! serves over HTTP (`server/rpc.rs`) and of the events it streams. `cargo test` rewrites
//! the file; CI checks that the checked-in copy is up to date.
//!
//! Each command becomes a function that calls `invoke` of `src/web/core.ts` with the
//! command name and its arguments under camelCase keys. A command that returns a
//! [`CommandResult`](crate::commands::CommandResult) resolves to `{ status: "ok", data }`
//! or `{ status: "error", error }`.

