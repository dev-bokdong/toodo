/// The commands of the bindings, for checking that the server serves each of them.
pub(crate) fn commands() -> Vec<Function> {
    collect_commands(&mut Types::default())
}

fn export() -> Result<(), Error> {
    let mut types = Types::default();
    let commands = collect_commands(&mut types);
    let events = collect_events(&mut types);
    // Results are unwrapped into `typedError` rather than exported as a type.
    types.iter_mut(|ndt| {
        if is_result(ndt) {
            ndt.ty = None;
        }
    });
    Exporter::from(Typescript::default())
        .framework_prelude(HEADER)
        .framework_runtime(move |exporter| runtime(exporter, &commands, &events))
        .export_to(PATH, &types, specta_serde::PhasesFormat)
}

fn runtime(
    mut exporter: FrameworkExporter,
    commands: &[Function],
    events: &[(&'static str, &'static str, DataType)],
) -> Result<Cow<'static, str>, Error> {
    let mut out = String::from(
        "import { invoke } from \"@/web/core\";\nimport { type EventCallback, listen } from \"@/web/event\";\n",
    );

    let mut functions = specta::datatype::Struct::named();
    for command in commands {
        let args = command
            .args()
            .iter()
            .map(|(name, dt)| {
                Ok((
                    name.to_lower_camel_case(),
                    render(dt, Phase::Deserialize, &exporter)?,
                ))
            })
            .collect::<Result<Vec<_>, Error>>()?;
        let params = args
            .iter()
            .map(|(name, ty)| format!("{name}: {ty}"))
            .collect::<Vec<_>>()
            .join(", ");
        let object = if args.is_empty() {
            String::new()
        } else {
            let keys = args
                .iter()
                .map(|(name, _)| name.as_str())
                .collect::<Vec<_>>();
            format!(", {{ {} }}", keys.join(", "))
        };
        let name = serde_json::to_string(command.name()).expect("a string serializes");
        let call = format!("({name}{object})");
        let body = match command
            .result()
            .and_then(|dt| std_result(dt, exporter.types))
        {
            Some((ok, err)) => format!(
                "typedError<{}, {}>(invoke{call})",
                render(ok, Phase::Serialize, &exporter)?,
                render(err, Phase::Serialize, &exporter)?
            ),
            None => format!(
                "invoke<{}>{call}",
                match command.result() {
                    Some(dt) => render(dt, Phase::Serialize, &exporter)?,
                    None => "void".to_owned(),
                }
            ),
        };
        let mut field = Field::new(define(format!("({params}) => {body}")).into());
        field.docs = command.docs.clone();
        field.deprecated = command.deprecated.clone();
        functions = functions.field(command.name().to_lower_camel_case(), field);
    }
    out.push_str("\n/** Commands */\nexport const commands = ");
    out.push_str(&inline(&functions.build(), &exporter)?);
    out.push_str(";\n");

    let mut listeners = specta::datatype::Struct::named();
    for (key, name, dt) in events {
        let payload = render(dt, Phase::Deserialize, &exporter)?;
        let name = serde_json::to_string(name).expect("a string serializes");
        let field = Field::new(define(format!("makeEvent<{payload}>({name})")).into());
        listeners = listeners.field(*key, field);
    }
    out.push_str("\n/** Events */\nexport const events = ");
    out.push_str(&exporter.inline(&listeners.build())?);
    out.push_str(";\n");

    let types = exporter.render_types()?;
    if !types.is_empty() {
        out.push_str("\n/* Types */");
        if !types.starts_with('\n') {
            out.push('\n');
        }
        out.push_str(&types);
    }

    out.push_str("\n/* Runtime */\n");
    out.push_str(RUNTIME);
    out.push('\n');
    Ok(Cow::Owned(out))
}

/// `dt` in the shape it has when the server serializes (results) or deserializes
/// (arguments) it, as a reference to its named type when it has one.
fn render(dt: &DataType, phase: Phase, exporter: &FrameworkExporter) -> Result<String, Error> {
    inline(
        &specta_serde::select_phase_datatype(dt, exporter.types, phase),
        exporter,
    )
}

fn inline(dt: &DataType, exporter: &FrameworkExporter) -> Result<String, Error> {
    match dt {
        DataType::Reference(r) => exporter.reference(r),
        dt => exporter.inline(dt),
    }
}

/// The success and error types of a `Result`.
fn std_result<'a>(dt: &'a DataType, types: &'a Types) -> Option<(&'a DataType, &'a DataType)> {
    if let DataType::Reference(Reference::Named(r)) = dt
        && let Some(ndt) = types.get(r)
        && is_result(ndt)
        && let NamedReferenceType::Reference { generics, .. } = &r.inner
        && let [(_, ok), (_, err), ..] = generics.as_slice()
    {
        return Some((ok, err));
    }
    None
}

fn is_result(ndt: &NamedDataType) -> bool {
    ndt.name == "Result" && matches!(&*ndt.module_path, "std::result" | "core::result")
}

const RUNTIME: &str = r#"async function typedError<T, E>(result: Promise<T>): Promise<{ status: "ok"; data: T } | { status: "error"; error: E }> {
    try {
        return { status: "ok", data: await result };
    } catch (e) {
        if (e instanceof Error) throw e;
        return { status: "error", error: e as any };
    }
}

function makeEvent<T>(name: string) {
    return {
        listen: (cb: EventCallback<T>) => listen<T>(name, cb),
    };
}"#;

